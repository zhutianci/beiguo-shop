/** 条款里的一条：普通条款是字符串；免除或者减轻平台责任、加重你的责任、限制你的权利的条款用 strong() 标记（页面加粗标色） */
export type TermsItem = string | { readonly text: string; readonly strong: true }

function strong(text: string): TermsItem {
  return Object.freeze({ text, strong: true as const })
}

/** 取一条的文字 */
export function itemText(it: TermsItem): string {
  return typeof it === 'string' ? it : it.text
}

/** 这一条要不要加粗标色 */
export function isStrong(it: TermsItem): boolean {
  return typeof it !== 'string' && it.strong === true
}

