/**
 * 兑换报错对照表。
 *
 * 【第一版的设计错误，别再犯】最初这份数据是直接照抄 sysa 适配器的
 * 中文提示表（src/lib/redeem/providers/sysa.ts 的 MESSAGES），
 * 并在落地页上宣称「这些是你在兑换页会看到的原话」。**那是错的**，两层错：
 *
 *   1. 站内注册了两家适配器（src/lib/redeem/registry.ts 的 `PROVIDERS = [sysa, sysb]`），
 *      两套文案完全不同。同一种情况，sysa 说「账号凭据无效或已过期」，
 *      sysb 说「账号凭据无效或不完整，请重新复制完整内容后再试」。
 *   2. 更要命的是，**多数档位根本不在站内兑换**。订单接口的优先级是
 *      `inSite = !!c.redeemProvider && hasProvider(...)`，否则回落到卡批的 redeemUrl
 *      或商品的 cardRedeemUrl（src/app/api/orders/route.ts）。线上实测：
 *      Claude Pro / Max、ChatGPT Plus 两档、ChatGPT Pro iOS 档、年费档
 *      全部配了外部兑换地址——那些买家看到的是第三方站点自己的措辞，
 *      和这两套文案一个字都不沾。
 *
 * 所以这份表**不能按「原话」组织**，只能按「情况」组织：
 * 每一行是一类真实会发生的失败，`seen` 里放我们这边已知的几种措辞变体
 * （精确字符串仍然有搜索价值，有人会整句粘进搜索框），
 * 但页面上必须说清楚：不同档位走不同通道，措辞不完全一样，按意思对号入座。
 *
 * 【维护约定】
 *   · sysa.ts 的 MESSAGES 或 sysb.ts 的 ERRORS 改了，回来核对这一份；
 *   · 只收录买家自己能判断、能做点什么的情况。纯内部故障不进表——
 *     把「请联系客服」翻译成一整段话对读者没有价值；
 *   · **绝对不要出现上游的品牌或域名**，货源是商业信息
 *     （见 src/app/(shop)/redeem/[provider]/page.tsx 的注释）。
 */

export interface RedeemError {
  /** 这一类失败是什么。第一列显示它 */
  situation: string
  /** 已知的几种实际措辞。不同通道不一样，列出来是为了让人能对上号 */
  seen: string[]
  /** 这句话到底在说什么 */
  meaning: string
  /** 该怎么办 */
  action: string
  /**
   * 卡密还能不能用——买家最关心的一列。
   *   safe    卡密不消耗
   *   depends 要看兑换页当时怎么说，不能一概而论
   */
  cardStatus: 'safe' | 'depends'
}

export interface RedeemErrorGroup {
  title: string
  intro: string
  items: RedeemError[]
}

