/**
 * 税号归一化。**零依赖的纯函数模块**，前台组件也能直接 import。
 *
 * 【为什么不放在 lib/invoice.ts】那个文件 import 了 node:crypto（genInvoiceNo 要用），
 * 客户端组件引它会把 crypto 打进浏览器包。而结算弹窗必须用**同一份**规则做前置校验——
 * 在组件里另写一遍 /\s/ 正则，就会出现「前台说 21 位不让下单、服务端算出来 18 位完全合法」
 * 这种买家怎么数都数不明白的偏差（JS 的 \\s 不含零宽字符）。
 */

/** 税号允许的最大长度。税局批量导入模板的硬限制，超了整批都导不进去 */
export const TAX_NUMBER_MAX_LEN = 20

/**
 * 抹掉**所有**空白与不可见字符。
 *
 * 买家常按四位一组敲成「9111 0108 MAER 0M7A 3L」，从 PDF/微信里粘贴还会带上
 * 全角空格、不换行空格与零宽字符。这些字符在页面上看不出来，却让税局批量导入
 * 报「购买方纳税人识别号长度不能超过20」—— 报错说的是长度，真凶是空格。
 *
 * 【只去空白，不改大小写】统一社会信用代码本就是大写，但把买家填的内容再做
 * 大小写转换属于额外改写，出了问题不好解释；长度校验交给调用方。
 */
export function normalizeTaxNumber(s: string | null | undefined): string {
  return (s || '').replace(/[\s\u3000\u00A0\u180E\u200B-\u200D\u2060\uFEFF]/g, '')
}
