/**
 * /support 上那 8 条常见问题。
 *
 * 【为什么要从页面里搬出来】/support 整页是 'use client'，
 * 而 FAQPage 结构化数据必须由服务端渲染进首屏 HTML（客户端注入的爬虫抓不到）。
 * 把数据抽成共享模块，页面与 layout 各取所需，两边永远是同一份内容——
 * 这一点是硬要求：Google 的结构化数据政策禁止标记「用户在页面上看不到的内容」，
 * 如果 JSON-LD 里的问答和页面上显示的对不上，那就是违规标记，不是小瑕疵。
 *
 * 【别指望它出富摘要】Google 2023 年 8 月起把 FAQ 富结果收窄到
 * 权威政府与健康类站点，普通商业站标了也不会在 SERP 里显示成折叠问答。
 * 它现在的价值是把问答关系讲清楚（对 AI 摘要与对话式检索仍然有用），
 * 以及顺带逼我们把这批问答维护成一份数据而不是散在 JSX 里。
 */
import type { StoreContact } from './contact-base'

export interface FAQItem {
  q: string
  a: string
}

/**
 * 第 1 条答案里「找谁」的那半句（二期改动 4.2：客服信息按店面取）。
 * 主站 = PLATFORM_CONTACT.wechat，拼出来与原文「请联系客服微信 GenuineMarxist」逐字相同；
 * 渠道只传了二维码（没填微信号）时不能写出一个空的微信号，改指向本页的「联系客服」弹窗，有客服邮箱就给邮箱。
 */
function whoToContact(c: StoreContact): string {
  if (c.wechat) return `请联系客服微信 ${c.wechat}`
  if (c.email) return `请发邮件到客服邮箱 ${c.email}`
  return '请点本页「联系客服」扫码添加客服'
}

