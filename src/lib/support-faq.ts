/**
 * 客服页「短信接码」分区（#jiema）与 /jiema 页 FAQ 用的参数：全部来自当前配置，文案里的数字与代码行为对得上（交接文档 1816 的教训）。
 *  · maxReplace：sms_config.maxReplace（收码前免费换号次数）；
 *  · complaintWindowH：sms_config.complaintWindowH（收码后多少小时内能申请售后）；
 *  · topup：wallet_config 的档位与单笔上下限（充值未开放 / 配置读不到时为 null，第 5 条改说「即将开放」）；
 *  · hours：店面客服在线时间（主站 9:00-22:00）。
 * 只在主站、而且接码对这个访客开放（或管理员预览）时渲染；渠道站不出现（D11）。
 */
export interface JiemaFaqParams {
  maxReplace: number
  complaintWindowH: number
  topup: { tiersCents: readonly number[]; minCents: number; maxCents: number } | null
  hours: string | null
}

const yuanInt = (cents: number) => {
  const y = Math.trunc(cents / 100)
  return y >= 1000 ? y.toLocaleString('en-US') : String(y)
}
const dashHours = (h: string | null) => (h || '9:00-22:00').replace(/(\d)\s*[-~]\s*(\d)/g, '$1–$2')

/** 分区顶部的「规则一览」（§8.3），与号码页 / 确认面板的说法一致 */
export function jiemaSupportRules(p: Pick<JiemaFaqParams, 'maxReplace' | 'complaintWindowH'>): string[] {
  return [
    '号码 20 分钟有效，取号 2 分钟后可换号或取消',
    `收到短信前可免费换号 ${p.maxReplace} 次；收到短信后不能换号或取消`,
    '可以用余额抵扣，余额不够的部分用支付宝补齐',
    '没收到短信：到期或取消后整单退回余额（含支付宝付的部分），下次购买可直接抵扣；退回的余额不能提现、不退回支付宝',
    `验证码无效等特殊情况：收码后 ${p.complaintWindowH} 小时内在订单页申请售后，人工审核`,
    '暂不支持开票，可联系客服开票处理',
  ]
}

