import { parseAmountDetailed, detectChannel } from '../src/lib/vmq'

const cases: [string, string][] = [
  ['①上一笔播报（必须拒绝）', '上一笔播报：支付宝到账 1430.00 元。收钱提醒助手正在为您服务'],
  ['②真实到账（必须取用）', '已转入余额 可兑1000收款免费额度>> 你已成功收款1430.00元（老顾客消费）'],
  ['③两条混在一起（应取真实那条）', '你已成功收款1430.00元（老顾客消费） 支付宝 已转入余额 可兑1000收款免费额度>> 你已成功收款1430.00元'],
  ['④只有播报被拼接', '支付宝 上一笔播报：支付宝到账 88.00 元。收钱提醒助手正在为您服务 支付宝到账 88.00 元'],
  ['⑤播报前缀+强信号（应拒绝）', '上一笔播报：你已成功收款999.00元'],
  ['⑥微信到账', '微信支付 你已成功收款12.34元'],
  ['⑦无关通知', '您有一条新的系统消息，请注意查收'],
  ['⑧带千分位', '你已成功收款1,430.00元'],
  ['⑨小额两位小数', '你已成功收款0.01元'],
]

for (const [name, text] of cases) {
  const r = parseAmountDetailed(text)
  const out = r.ok ? `取用 ${r.amount} 元 (${detectChannel(text) === 1 ? '微信' : '支付宝'})` : `拒绝 [${r.reason}]`
  console.log(name.padEnd(30, '　'), '=>', out)
}
